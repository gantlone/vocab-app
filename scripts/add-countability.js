// Build a lookup that also handles slash-variants: "airplane/plane" → check "airplane" and "plane"
function lookupCountability(wordField) {
  const variants = wordField.toLowerCase()
    .replace(/\s*\(.*?\)/g, '')  // remove (2), (1) etc
    .split('/')
    .map(v => v.trim())
  for (const v of variants) {
    if (COUNTABILITY[v]) return COUNTABILITY[v]
  }
  return null
}

// Inject countability tag into pos string (only for 'n.' parts)
function injectUC(pos, tag) {
  if (/n\.\[/.test(pos)) return pos
  return pos.replace(/\bn\./, `n.[${tag}]`)
}

async function run() {
  const ucMap  = JSON.parse(await fs.readFile(UC_MAP_PATH, 'utf-8'))
  const rawVocab = await fs.readFile(VOCAB_PATH, 'utf-8')
  const vocab  = JSON.parse(rawVocab)

  let fromPDF = 0, fromTable = 0, defaultC = 0, unchanged = 0

  for (const page of Object.values(vocab.pages)) {
    for (const w of page.words) {
      if (!w.pos.includes('n.')) continue
      if (/n\.\[/.test(w.pos)) { unchanged++; continue }

      // Priority 1: PDF markers
      if (ucMap[w.id]) {
        w.pos = injectUC(w.pos, ucMap[w.id])
        fromPDF++
        continue
      }

      // Priority 2: knowledge table
      const tag = lookupCountability(w.word)
      if (tag) {
        w.pos = injectUC(w.pos, tag)
        fromTable++
        continue
      }

      // Priority 3: default to [C] if flag is set
      if (DEFAULT_C) {
        w.pos = injectUC(w.pos, 'C')
        defaultC++
      }
    }
  }

  if (DRY_RUN) {
    console.log('\n=== DRY RUN — 不寫入檔案 ===')
    let shown = 0
    for (const page of Object.values(vocab.pages))
      for (const w of page.words)
        if (/n\.\[/.test(w.pos) && shown++ < 40)
          console.log(w.word.padEnd(24), '|', w.pos)
    const untagged = Object.values(vocab.pages)
      .flatMap(p => p.words)
      .filter(w => w.pos.includes('n.') && !/n\.\[/.test(w.pos))
    console.log(`\n來源 PDF：${fromPDF}  來源知識表：${fromTable}  預設[C]：${defaultC}  已有標記跳過：${unchanged}`)
    console.log(`無法辨別（不標）：${untagged.length}`)
    if (!DEFAULT_C && untagged.length > 0) {
      console.log(`（加 --default-C 旗標可將剩餘 ${untagged.length} 個名詞全標為 [C]）`)
    }
  } else {
    await fs.writeFile(VOCAB_PATH, JSON.stringify(vocab, null, 2), 'utf-8')
    console.log(`\nDone!  來源 PDF：${fromPDF}  來源知識表：${fromTable}  預設[C]：${defaultC}`)
    console.log(`總標記：${fromPDF + fromTable + defaultC}  已有標記跳過：${unchanged}`)
  }
}

run().catch(err => { console.error(err); process.exit(1) })
